export function herRhythmLine(msgs, nowMs = Date.now()) {
  const list = Array.isArray(msgs) ? msgs : [];
  const windowMs = 3 * 24 * 60 * 60 * 1000;
  const byHour = new Array(24).fill(0);
  let total = 0;
  for (const m of list) {
    if (!m || !m.isSelf) continue;
    const t = Number(m.time) || 0;
    if (!t || nowMs - t > windowMs || t > nowMs + 60000) continue;
    byHour[new Date(t).getHours()] += 1;
    total += 1;
  }
  if (total < 6) return '';   // 数据太少，别硬编

  // 找最活跃的连续 3 小时窗口
  let bestAt = 0;
  let bestSum = -1;
  for (let h = 0; h < 24; h++) {
    const sum = byHour[h] + byHour[(h + 1) % 24] + byHour[(h + 2) % 24];
    if (sum > bestSum) { bestSum = sum; bestAt = h; }
  }
  const pad = (n) => String(n).padStart(2, '0');
  const span = `${pad(bestAt)}-${pad((bestAt + 2) % 24)} 点`;   // 3 小时窗口 = 起止都含
  // 深夜（0-5 点）说了几句 —— 这是她"作息散架"的唯一证据
  const night = byHour[0] + byHour[1] + byHour[2] + byHour[3] + byHour[4] + byHour[5];
  return `【你最近的活动】过去三天你说了 ${total} 句，最多的是 ${span}（${bestSum} 句）`
    + (night >= 3 ? `；凌晨 0-6 点还有 ${night} 句` : '')
    + '。\n（这只是记录，没有"该不该"—— 你自己看要不要调整。）\n\n';
}

